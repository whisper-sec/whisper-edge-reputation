"""gen-abi-layout.py - the module ABI held to its layout.

Every public struct of we_module.h, and of we_procid.h (whose we_procid_t crosses we_module.c's boundary
as we_mod_procid_t), is measured by the compiler (sizeof, and offsetof of every field) and the figures are
written into each header between its ABI-LAYOUT markers as static asserts, beside the
WE_MODULE_ABI_VERSION they were measured under. THE RULE (we_module.h's ABI comment): under one major an
ADDED declaration is compatible, so new assertions are written without a new major; a CHANGED or
REMOVED layout (a recorded assertion the compiler no longer measures) fails to compile, and this script
refuses to write it until the major moves.

    gen-abi-layout.py --check      every block equals a fresh measurement (make check runs it)
    gen-abi-layout.py --write      rewrite the blocks; refused when a recorded layout changed under one major
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.environ.get('WE_ABI_HEADER', os.path.join(HERE, 'we_module.h'))
PROCID = os.environ.get('WE_ABI_PROCID', os.path.join(HERE, 'we_procid.h'))
BEGIN = '/* ---- ABI-LAYOUT: generated by gen-abi-layout.py from the compiler\'s own measurement; do not edit ---- */'
END = '/* ---- ABI-LAYOUT end ---- */'


def structs(text):
    """(name, [field, ...]) for every `typedef struct {...} name;`, top-level fields only"""
    out = []
    for m in re.finditer(r'typedef struct(?: \w+)? \{', text):
        start = m.end()
        depth, j = 1, start
        while depth:
            depth += {'{': 1, '}': -1}.get(text[j], 0)
            j += 1
        body = text[start:j - 1]
        name = re.match(r'\s*(\w+)\s*;', text[j:]).group(1)
        flat, d, buf = [], 0, ''
        for ch in re.sub(r'/\*.*?\*/', '', body, flags=re.S):
            if ch == '{':
                d += 1
            elif ch == '}':
                d -= 1
            if d == 0 and ch == ';':
                flat.append(buf)
                buf = ''
            elif d == 0:
                buf += ch
        fields = []
        for decl in flat:
            decl = re.sub(r'#[^\n]*', '', decl)
            decl = ' '.join(decl.split())
            if not decl:
                continue
            decl = re.sub(r'\bWE_ALIGN64\b', '', decl)
            for part in decl.split(','):
                part = re.sub(r'\[[^\]]*\]', '', part)
                part = re.sub(r'\(\s*\*\s*(\w+)\s*\)\s*\(.*', r'\1', part)
                mm = re.search(r'(\w+)\s*$', part.strip())
                if mm:
                    fields.append(mm.group(1))
        out.append((name, fields))
    return out


def measure(text, include='we_module.h', path=None):
    ss = structs(text)
    prog = ['#define _GNU_SOURCE 1', '#define WE_MOD_ABI_LAYOUT_MEASURING 1', '#include <stddef.h>', '#include "%s"' % include,
            '#include <stdio.h>', 'int main(void) {']
    for name, fields in ss:
        prog.append('printf("S %s %%zu %%zu\\n", sizeof(%s), _Alignof(%s));' % (name, name, name))
        for f in fields:
            prog.append('printf("F %s %s %%zu\\n", offsetof(%s, %s));' % (name, f, name, f))
    prog.append('return 0; }')
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, 'm.c')
        open(src, 'w').write('\n'.join(prog) + '\n')
        exe = os.path.join(d, 'm')
        shutil.copy(path or HEADER, os.path.join(d, include))
        subprocess.run([os.environ.get('CC', 'cc'), '-std=c11', '-I', d, '-I', HERE, '-o', exe, src], check=True)
        return subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split('\n')


def block_procid(lines, abi):
    """we_procid.h's block: plain _Static_assert (the header stands alone), the major recorded beside it"""
    out = [BEGIN, '/* measured under WE_MODULE_ABI_VERSION %s: a change here is a change of the module ABI */' % abi,
           '#if !defined(WE_MOD_ABI_LAYOUT_MEASURING)', '#define WE_PROCID_ABI_LAYOUT_MAJOR %su' % abi]
    for l in lines:
        w = l.split()
        if not w:
            continue
        if w[0] == 'S':
            out.append('_Static_assert(sizeof(%s) == %su && _Alignof(%s) == %su, "%s: ABI layout");'
                       % (w[1], w[2], w[1], w[3], w[1]))
        else:
            out.append('_Static_assert(offsetof(%s, %s) == %su, "%s.%s: ABI layout");' % (w[1], w[2], w[3], w[1], w[2]))
    out += ['#endif', END]
    return '\n'.join(out)


def block(lines, abi):
    out = [BEGIN,
           '/* not in a WE_TRACE build: the trace build is a test build whose scratch carries the trace\'s own',
           ' * fields; it never ships, and the release layout is the one a module is built against */',
           '#if !defined(WE_MOD_ABI_LAYOUT_MEASURING) && !defined(WE_TRACE)', '#define WE_MOD_ABI_LAYOUT_MAJOR %su' % abi,
           'WE_STATIC_ASSERT(WE_MODULE_ABI_VERSION == WE_MOD_ABI_LAYOUT_MAJOR, '
           '"the layout below was measured under another major: regenerate it with gen-abi-layout.py --write");',
           'WE_STATIC_ASSERT(sizeof(void *) == 8u, "the module ABI is LP64");']
    for l in lines:
        w = l.split()
        if not w:
            continue
        if w[0] == 'S':
            out.append('WE_STATIC_ASSERT(sizeof(%s) == %su && _Alignof(%s) == %su, "%s: ABI layout");'
                       % (w[1], w[2], w[1], w[3], w[1]))
        else:
            out.append('WE_STATIC_ASSERT(offsetof(%s, %s) == %su, "%s.%s: ABI layout");' % (w[1], w[2], w[3], w[1], w[2]))
    out += ['#endif', END]
    return '\n'.join(out)


def one(path, include, builder, abi):
    """(text, a, b, old, new) for one header's block"""
    text = open(path).read()
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < 0:
        sys.exit('gen-abi-layout: %s has no ABI-LAYOUT markers' % os.path.basename(path))
    return text, a, b, text[a:b + len(END)], builder(measure(text, include, path), abi)


def main():
    abi = re.search(r'#define WE_MODULE_ABI_VERSION (\d+)u', open(HEADER).read()).group(1)
    files = [(HEADER, 'we_module.h', block), (PROCID, 'we_procid.h', block_procid)]
    res = [(path,) + one(path, inc, bld, abi) for path, inc, bld in files]
    # THE RULE the header states: under one major, an ADDED declaration (a new type, so new assert lines)
    # is compatible; a CHANGED or REMOVED one (an old assert line no longer measured) needs a new major
    asserts = lambda x: [l for l in x.split('\n') if 'ABI layout")' in l]
    gone, added, nstruct, nfield = [], 0, 0, 0
    for path, text, a, b, old, new in res:
        om = re.search(r'#define WE_(?:MOD|PROCID)_ABI_LAYOUT_MAJOR (\d+)u', old)
        if om is not None and om.group(1) == abi:
            gone += [l for l in asserts(old) if l not in set(asserts(new))]
        added += len([l for l in asserts(new) if l not in set(asserts(old))])
        nstruct += new.count('_Alignof(')
        nfield += new.count('offsetof(')
    if sys.argv[1:] == ['--check']:
        stale = [os.path.basename(r[0]) for r in res if r[4] != r[5]]
        if stale:
            if gone:
                print('FAIL abi layout: a recorded layout changed or went under ABI %s (%s): raise WE_MODULE_ABI_VERSION '
                      'and run gen-abi-layout.py --write' % (abi, gone[0][:90]))
            else:
                print('FAIL abi layout: %s\'s ABI-LAYOUT block is not the compiler\'s measurement (%d added assertions, '
                      'nothing recorded changed): run gen-abi-layout.py --write; the major stays %s'
                      % (' and '.join(stale), added, abi))
            sys.exit(1)
        print('ok   abi layout: %d structs and their %d fields as recorded under ABI %s (we_module.h and we_procid.h)'
              % (nstruct, nfield, abi))
        print('1 checks, 0 failures')
        return
    if sys.argv[1:] == ['--write']:
        if gone:
            sys.exit('gen-abi-layout: a recorded layout changed or went and WE_MODULE_ABI_VERSION is still %s: raise the '
                     'major first (%s)' % (abi, gone[0][:90]))
        for path, text, a, b, old, new in res:
            if old != new:
                open(path, 'w').write(text[:a] + new + text[b + len(END):])
        print('wrote the ABI-LAYOUT blocks under ABI %s (%d assertions added)' % (abi, added))
        return
    sys.exit('usage: gen-abi-layout.py --check | --write')


if __name__ == '__main__':
    main()
