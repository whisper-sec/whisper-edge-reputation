"""
gen-country-table.py - the known-code bitmap whisper_edge.c compiles in, from the ISO 3166-1 list,
and the alpha-2 column the policy compiler reads.

A routing record's `country` is an ISO 3166-1 numeric code. A code in 1..999 that the reader's table
does not know is read as `undetermined` rather than refused (FORMAT.md 3.1), because a plane built
against a newer table must never make a module refuse the whole plane over one new assignment. So the
reader carries a 1,000-bit bitmap of the codes it knows: 125 bytes, hot in L1, one load.

The request path's renderer (we_module.h) reads a third form, behind WE_COUNTRY_DIRECT: the alpha-2
spelling indexed directly by the numeric code, 1,000 entries of 3 bytes, so a country renders with one
compare and one index instead of a scan. A translation unit that wants only that table defines
WE_COUNTRY_DIRECT_ONLY as well, and carries neither of the other two.

The policy language writes countries as alpha-2 codes (`country in { NL BE }`) and compiles them to
the numeric code a record carries, so the same table also emits the alpha-2 column, sorted for a
binary search, behind WE_COUNTRY_ALPHA2: only the compiler reads it, and a translation unit that does
not define the macro does not carry an unused array.

The list is the Debian/Ubuntu iso-codes package's iso_3166-1.json, which tracks the ISO 3166
Maintenance Agency. The four user-assigned codes FORMAT.md gives a meaning (900 EU, 901 AP, 902 ZZ,
903 XK) are added, because the builder writes them.

Usage:
    gen-country-table.py [path/to/iso_3166-1.json] [YYYYMM]

Prints the C table to stdout. The YYYYMM is the version the table is stamped with, written as
YYYYMM mod 65536 like the header field it is compared with.
"""
import json
import sys

USER_ASSIGNED = {900: "EU", 901: "AP", 902: "ZZ", 903: "XK"}


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/iso-codes/json/iso_3166-1.json"
    yyyymm = int(sys.argv[2]) if len(sys.argv) > 2 else 202312
    with open(path, encoding="utf-8") as f:
        rows = json.load(f)["3166-1"]
    codes = sorted({int(r["numeric"]) for r in rows} | set(USER_ASSIGNED))
    assert all(0 < c <= 999 for c in codes), "a code outside 1..999"
    alpha = {r["alpha_2"]: int(r["numeric"]) for r in rows}
    for num, a2 in USER_ASSIGNED.items():
        assert a2 not in alpha, "a user-assigned alpha-2 collides with an assigned code"
        alpha[a2] = num
    assert all(len(a) == 2 and a.isalpha() and a.isupper() for a in alpha), "an alpha-2 that is not two letters"
    assert len(set(alpha.values())) == len(alpha), "two alpha-2 codes share a numeric code"
    bits = bytearray(125)
    for c in codes:
        bits[c >> 3] |= 1 << (c & 7)
    print("/*\n * SPDX-License-Identifier: MIT\n * Copyright (c) 2026, viaGraph B.V.\n *\n"
          " * The ISO 3166-1 numeric codes this reader knows, as a 1,000-bit bitmap. GENERATED: regenerate\n"
          " * with `make country-table`, never by hand. Included by whisper_edge.c, and by the policy\n"
          " * compiler, which also reads the alpha-2 column below (define WE_COUNTRY_ALPHA2 first).\n */")
    print("#ifndef WE_COUNTRY_DIRECT_ONLY")
    print("#ifndef WE_COUNTRY_TABLE_H\n#define WE_COUNTRY_TABLE_H\n")
    print("/* Generated by gen-country-table.py from %s: %d ISO 3166-1 codes plus %s. */"
          % (path.rsplit("/", 1)[-1], len(codes) - len(USER_ASSIGNED),
             ", ".join("%d %s" % kv for kv in sorted(USER_ASSIGNED.items()))))
    print("#define WE_COUNTRY_TABLE_YYYYMM %du" % yyyymm)
    print("#define WE_COUNTRY_TABLE_VERSION %du   /* YYYYMM mod 65536 */" % (yyyymm % 65536))
    print("#define WE_COUNTRY_TABLE_CODES %du" % len(codes))
    print("static const uint8_t we_country_known_table[125] = {")
    for i in range(0, 125, 16):
        print("    " + ", ".join("0x%02x" % b for b in bits[i:i + 16]) + ",")
    print("};")
    print("\n#ifdef WE_COUNTRY_ALPHA2")
    print("/* The alpha-2 spelling of every known code, sorted by spelling for a binary search. */")
    print("typedef struct { char a2[2]; uint16_t num; } we_country_alpha2_t;")
    print("#define WE_COUNTRY_ALPHA2_COUNT %du" % len(alpha))
    print("static const we_country_alpha2_t we_country_alpha2_table[%d] = {" % len(alpha))
    items = sorted(alpha.items())
    for i in range(0, len(items), 6):
        print("    " + " ".join("{ { '%s', '%s' }, %3d }," % (a[0], a[1], n) for a, n in items[i:i + 6]))
    print("};\n#endif /* WE_COUNTRY_ALPHA2 */")
    print("\n#endif /* WE_COUNTRY_TABLE_H */")
    print("#endif /* WE_COUNTRY_DIRECT_ONLY */")
    # The request path's renderer: the alpha-2 spelling indexed directly by the numeric code, one entry
    # per code 0..999, a gap (and code 0) the empty string. The renderer's one compare keeps every index
    # below 1,000, so a raw block's 16-bit field can never read past the table.
    by_num = {n: a for a, n in alpha.items()}
    print("\n#if defined(WE_COUNTRY_DIRECT) && !defined(WE_COUNTRY_DIRECT_H)")
    print("#define WE_COUNTRY_DIRECT_H")
    print("/*\n * Entry `code` is that numeric code's alpha-2 spelling, NUL-terminated, or \"\" for a code this table")
    print(" * does not know and for 0. 1,000 entries: the CALLER compares the code with 999 before it indexes,")
    print(" * because a raw 16-bit field can hold 65,535 (we_module.h's renderer is the one caller).\n */")
    print("typedef char we_country_a2_t[3];")
    print("static inline const we_country_a2_t *we_country_a2_table(void)\n{")
    print("    static const we_country_a2_t t[1000] = {")
    for i in range(0, 1000, 10):
        row = []
        for c in range(i, i + 10):
            a = by_num.get(c)
            row.append('"%s"' % a if a else '""')
        print("        " + ", ".join(row) + ",")
    print("    };\n")
    print("    return t;")
    print("}")
    print("#endif /* WE_COUNTRY_DIRECT */")


if __name__ == "__main__":
    main()
