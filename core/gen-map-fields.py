"""gen-map-fields.py - every pointer field of we_map_t, found by a scan of whisper_edge.h.

we_map_rebase() moves a verified view from the buffer it was checked in to the mapping it serves from,
field by field. A field it misses keeps pointing into the old buffer, which is freed: a use after free
that no reader would see until the bytes were reused. test_core's rebase row fills every field this scan
finds and asserts each one moved, so a pointer added to we_map_t (or we_fam_t, whose three members are
expanded) is held by the row without anyone remembering to list it, and make check refuses a committed
list that differs from the scan (a planted omission is its control). `base` is the anchor the rebase
moves last and is not listed.

    gen-map-fields.py               print the list (we_map_fields.h's contents)
    gen-map-fields.py --check       the committed we_map_fields.h equals the scan
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def body(text, name):
    end = text.find('\n} %s;' % name)
    start = text.rfind('typedef struct {', 0, end)
    if end < 0 or start < 0:
        sys.exit('gen-map-fields: no typedef struct %s in whisper_edge.h' % name)
    return re.sub(r'/\*.*?\*/', '', text[start + len('typedef struct {'):end], flags=re.S)


def fields(src):
    """(type, name, is_pointer) for every member declaration"""
    out = []
    for decl in src.split(';'):
        decl = ' '.join(decl.split())
        if not decl or decl.startswith('#'):
            continue
        if '(' in decl:
            sys.exit('gen-map-fields: a function pointer in the struct is not a view pointer: %s' % decl)
        for i, part in enumerate(decl.split(',')):
            part = re.sub(r'\[[^\]]*\]', '', part).strip()
            mm = re.match(r'(.*?)([\s*]+)(\w+)$', part) if i == 0 else re.match(r'()([\s*]*)(\w+)$', part)
            if mm is None:
                sys.exit('gen-map-fields: cannot read the member %r' % part)
            out.append((mm.group(1).strip(), mm.group(3), '*' in mm.group(2)))
    return out


def scan(text):
    fam = [n for t, n, p in fields(body(text, 'we_fam_t')) if p]
    lines = []
    for t, n, p in fields(body(text, 'we_map_t')):
        if t == 'we_fam_t' and not p:
            lines += ['WE_MAP_FIELD(%s.%s)' % (n, f) for f in fam]
        elif p and n != 'base':
            lines.append('WE_MAP_FIELD(%s)' % n)
    return ('/* SPDX-License-Identifier: MIT */\n/* Copyright (c) 2026, viaGraph B.V. */\n'
            '/* generated by gen-map-fields.py from whisper_edge.h: every pointer field of we_map_t (we_fam_t\'s\n'
            ' * expanded), base excepted; do not edit */\n' + '\n'.join(lines) + '\n')


def main():
    text = open(os.path.join(HERE, 'whisper_edge.h')).read()
    out = scan(text)
    if sys.argv[1:] == ['--check']:
        path = os.environ.get('WE_MAP_FIELDS', os.path.join(HERE, 'we_map_fields.h'))
        if open(path).read() != out:
            print('FAIL map fields: %s is not the scan of we_map_t\'s pointer fields; run gen-map-fields.py > '
                  'we_map_fields.h' % os.path.basename(path))
            sys.exit(1)
        print('ok   map fields: we_map_fields.h is the scan of we_map_t\'s %d pointer fields' % out.count('WE_MAP_FIELD('))
        print('1 checks, 0 failures')
        return
    if sys.argv[1:]:
        sys.exit('usage: gen-map-fields.py [--check]')
    sys.stdout.write(out)


main()
