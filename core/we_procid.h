/* field 22 of /proc/self/stat, after the parenthesised command, which may hold spaces */
static inline int we_proc_starttime(uint64_t *st)
{
    char buf[1024], *p;
    int fd = open("/proc/self/stat", O_RDONLY | O_CLOEXEC), k;
    ssize_t n;

    if (fd < 0) {
        return -1;
    }
    n = read(fd, buf, sizeof buf - 1u);
    close(fd);
    if (n <= 0) {
        return -1;
    }
    buf[n] = '\0';
    p = strrchr(buf, ')');
    for (k = 2; k < 22 && p != NULL; k++) {
        p = strchr(p + 1, ' ');
    }
    if (p == NULL) {
        return -1;
    }
    *st = strtoull(p + 1, NULL, 10);
    return 0;
}

