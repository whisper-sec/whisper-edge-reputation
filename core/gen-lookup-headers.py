"""
gen-lookup-headers.py - the generated headers whisper-edge-lookup compiles in.

Each header is committed, so a build needs no Python, and `make check-lookup` regenerates every one and
diffs it against the committed copy, so a header nobody regenerated fails the build instead of drifting.
Every input is a file of this tree, because this tree is what ships.

    gen-lookup-headers.py cite <hold-harmless.txt> [--published <README.md>]
                                                          we_hold_harmless_cite.h; with --published, the
                                                          list's distinct-prefix count must equal the one
                                                          the README states, or nothing is generated
    gen-lookup-headers.py default-policy <default.conf>  we_default_policy.h
    gen-lookup-headers.py guard <file>...                 we_lookup_guard.h

cite: every entry of the hold-harmless list in file order, with its source column (the method) and its
description (the note), and the merged ranges the evaluator builds from the same file: entries sorted
and joined when they overlap or touch, so the range the tool prints is the range step 1 matches.

default-policy: the shipped default policy, byte for byte, as a C string.

guard: one #error per mutant name (WE_TEST_* and WE_LOOKUP_TEST_*) found in the given files, so the
shipped tool refuses to compile with any of them defined unless the build says it is a mutant build.
"""
import ipaddress
import re
import sys

HEADER = ("/*\n * SPDX-License-Identifier: MIT\n * Copyright (c) 2026, viaGraph B.V.\n *\n"
          " * GENERATED by gen-lookup-headers.py %s from %s: regenerate with `make %s`, never by hand.\n"
          " * `make check-lookup` regenerates it and fails when the committed copy differs.\n */")


def c_string(data):
    """A byte string as a C string literal body: printable ASCII as itself, every other byte as \\ooo."""
    out = []
    for b in data:
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif b == 0x0A:
            out.append("\\n")
        elif 0x20 <= b <= 0x7E and b != 0x3F:      # '?' escaped too, so no trigraph can form
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return "".join(out)


def be_bytes(addr, family):
    raw = addr.packed
    return raw + bytes(16 - len(raw)) if family == 4 else raw


def c_bytes(b):
    return "{" + ",".join("0x%02x" % x for x in b) + "}"


def merge(ranges):
    ranges = sorted(ranges)
    out = []
    for s, e in ranges:
        if out and s <= out[-1][1] + 1:
            out[-1][1] = max(out[-1][1], e)
        else:
            out.append([s, e])
    return out


def published_distinct(readme):
    """The distinct-prefix count the README publishes for the list, or None when it states none."""
    m = re.search(r"([0-9,]+) distinct prefixes", open(readme, encoding="utf-8").read())
    return int(m.group(1).replace(",", "")) if m else None


def cite(path, readme=None):
    entries = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            parts = body.split(None, 2)
            if len(parts) < 2:
                raise SystemExit("%s: an entry needs an address and a source: %r" % (path, body))
            net = ipaddress.ip_network(parts[0], strict=True)
            entries.append((parts[0], net, parts[1], parts[2] if len(parts) > 2 else ""))
    distinct = len({n for _, n, _, _ in entries})
    if readme is not None:
        said = published_distinct(readme)
        if said is None:
            raise SystemExit("%s states no distinct-prefix count for the hold-harmless list" % readme)
        if said != distinct:
            raise SystemExit("%s publishes %d distinct prefixes and %s holds %d" % (readme, said, path, distinct))
    print(HEADER % ("cite", "../hold-harmless.txt", "lookup-headers"))
    print("#ifndef WE_HOLD_HARMLESS_CITE_H\n#define WE_HOLD_HARMLESS_CITE_H\n")
    print("#include <stdint.h>\n")
    print("/* An entry of the list: its family, first and last address (network order, IPv4 in bytes 0..3),")
    print(" * the entry as written, its source column and its description. */")
    print("typedef struct {\n    uint8_t     family;\n    uint8_t     start[16];\n    uint8_t     end[16];"
          "\n    const char *entry;\n    const char *method;\n    const char *note;\n} we_hh_cite_t;\n")
    print("typedef struct {\n    uint8_t family;\n    uint8_t start[16];\n    uint8_t end[16];\n} we_hh_range_t;\n")
    print("/* %d entries, %d distinct prefixes (the count the README publishes, asserted at generation). */"
          % (len(entries), distinct))
    print("#define WE_HH_CITE_COUNT %du" % len(entries))
    print("#define WE_HH_CITE_DISTINCT %du" % distinct)
    print("static const we_hh_cite_t we_hh_cites[%d] = {" % len(entries))
    for text, net, method, note in entries:
        fam = net.version
        print("    { %d, %s,\n         %s,\n      \"%s\", \"%s\", \"%s\" }," % (
            fam, c_bytes(be_bytes(net.network_address, fam)), c_bytes(be_bytes(net.broadcast_address, fam)),
            c_string(text.encode()), c_string(method.encode()), c_string(note.encode())))
    print("};\n")
    merged = []
    for fam in (4, 6):
        rs = [(int(n.network_address), int(n.broadcast_address)) for _, n, _, _ in entries if n.version == fam]
        for s, e in merge(rs):
            cls = ipaddress.IPv4Address if fam == 4 else ipaddress.IPv6Address
            merged.append((fam, cls(s), cls(e)))
    print("/* The merged ranges, IPv4 then IPv6, each family sorted: overlapping and touching entries joined. */")
    print("#define WE_HH_RANGE_COUNT %du" % len(merged))
    print("static const we_hh_range_t we_hh_ranges[%d] = {" % len(merged))
    for fam, s, e in merged:
        print("    { %d, %s,\n         %s }," % (fam, c_bytes(be_bytes(s, fam)), c_bytes(be_bytes(e, fam))))
    print("};\n")
    print("#endif /* WE_HOLD_HARMLESS_CITE_H */")


def default_policy(path):
    with open(path, "rb") as f:
        data = f.read()
    print(HEADER % ("default-policy", "testdata/policy/default.conf", "lookup-headers"))
    print("#ifndef WE_DEFAULT_POLICY_H\n#define WE_DEFAULT_POLICY_H\n")
    print("/* The shipped default policy, %d bytes, exactly as testdata/policy/default.conf holds it. */"
          % len(data))
    print("#define WE_DEFAULT_POLICY_LEN %du" % len(data))
    print("static const char we_default_policy[] =")
    for line in data.splitlines(keepends=True):
        print('    "%s"' % c_string(line))
    print("    ;\n")
    print("#endif /* WE_DEFAULT_POLICY_H */")


def guard(paths):
    names = set()
    for p in paths:
        with open(p, encoding="utf-8", errors="replace") as f:
            names.update(re.findall(r"\bWE_(?:LOOKUP_)?TEST_[A-Z0-9_]+", f.read()))
    print(HEADER % ("guard", "the tool's compile inputs", "gen-lookup-guard"))
    print("#ifndef WE_LOOKUP_GUARD_H\n#define WE_LOOKUP_GUARD_H\n")
    print("/*")
    print(" * The shipped whisper-edge-lookup refuses every test mutant: a build defining WE_LOOKUP_TOOL and")
    print(" * any name below fails here unless it also defines WE_LOOKUP_MUTANT_BUILD, which only the gate's")
    print(" * mutant phase does. The Makefile refuses the same names on the command line; this is the second")
    print(" * wall, for a definition that arrives some other way. %d names." % len(names))
    print(" */")
    for n in sorted(names):
        print("#if defined(WE_LOOKUP_TOOL) && !defined(WE_LOOKUP_MUTANT_BUILD) && defined(%s)" % n)
        print("#error \"%s is a test mutant; the shipped whisper-edge-lookup is never built with one\"" % n)
        print("#endif")
    print("\n#endif /* WE_LOOKUP_GUARD_H */")


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__.strip())
    what = sys.argv[1]
    if what == "cite":
        rest = sys.argv[3:]
        cite(sys.argv[2], rest[1] if len(rest) == 2 and rest[0] == "--published" else None)
    elif what == "default-policy":
        default_policy(sys.argv[2])
    elif what == "guard":
        guard(sys.argv[2:])
    else:
        raise SystemExit("unknown header %r: cite, default-policy or guard" % what)


if __name__ == "__main__":
    main()
