"""cg-statics.py - the cachegrind driver's file-scope static objects, found by a scan of its source.

A D1 count is the code's only when every object the measured loops read starts a page: a static that
follows the link's layout moves its cache sets with any change to any linked unit. The driver checks
the alignment at run time over a list; this script writes that list from the source, so a static added
to the driver is in the list without anyone remembering to add it, and the gate refuses a committed
list that differs from the scan (a planted omission is its control).

Every file-scope object declared `static` is listed, const or not, by name, inside the same
preprocessor conditionals it is declared under; functions are not objects and are skipped. Function-scope
statics are out of the scan's reach and the driver's measured functions declare none.

    cg-statics.py gate/cg_driver.c            print the list (gate/cg_statics.h's contents)
"""
import re
import sys


def scan(text):
    out = []
    depth = 0                       # brace depth: 0 is file scope
    cond = []                       # the preprocessor conditionals open at file scope
    buf = None                      # a static declaration being collected, until its `;` at depth 0
    bdepth = 0
    for line in text.splitlines():
        s = line.strip()
        if depth == 0 and buf is None and re.match(r'#\s*(if|ifdef|ifndef)\b', s):
            cond.append(s)
            out.append(s)
            continue
        if depth == 0 and buf is None and re.match(r'#\s*(else|elif)\b', s):
            out.append(s)
            continue
        if depth == 0 and buf is None and re.match(r'#\s*endif\b', s):
            if cond:
                cond.pop()
            out.append(s)
            continue
        if depth == 0 and buf is None and line.startswith('static '):
            buf = ''
            bdepth = 0
        if buf is not None:
            code = re.sub(r'/\*.*?\*/', '', line)
            code = re.sub(r'"(\\.|[^"\\])*"', '""', code)
            code = re.sub(r"'(\\.|[^'\\])*'", "''", code)
            buf += code + '\n'
            bdepth += code.count('{') - code.count('}')
            if bdepth <= 0 and ';' in code and bdepth == 0 and buf.count('{') == buf.count('}'):
                out.extend(names(buf))
                buf = None
            elif bdepth > 0 and '(' in buf.split('{', 1)[0] and '=' not in buf.split('{', 1)[0]:
                # a function definition: not an object; skip its body
                depth = bdepth
                buf = None
            continue
        code = re.sub(r'"(\\.|[^"\\])*"', '""', re.sub(r'/\*.*?\*/', '', line))
        depth += code.count('{') - code.count('}')
    return out


def names(decl):
    """the declarators of one `static ...;` at file scope; nothing for a prototype"""
    d = ' '.join(decl.split()).rstrip(';').strip()
    prev = None
    while '{' in d and d != prev:          # every brace group, innermost first: struct bodies, initialisers
        prev = d
        d = re.sub(r'\{[^{}]*\}', ' ', d)
    head = d.split('=', 1)[0]
    if '(' in re.sub(r'__attribute__\s*\(\(.*?\)\)', '', head) and not re.search(r'\(\s*\*', head):
        return []                          # a prototype
    d = re.sub(r'^static\s+', '', d)
    found = []
    for part in d.split(','):
        part = part.split('=', 1)[0]
        part = re.sub(r'__attribute__\s*\(\(.*?\)\)|\bWE_CG_PAGE\b', '', part)
        part = re.sub(r'\[[^\]]*\]', '', part)
        part = re.sub(r'[()*]', ' ', part).strip()     # a pointer to an array: (*name)[16]
        m = re.search(r'([A-Za-z_]\w*)\s*$', part)
        if m and m.group(1) not in ('const', 'volatile', 'struct'):
            found.append('CG_STATIC(%s)' % m.group(1))
    return found


def main():
    text = open(sys.argv[1]).read()
    body = scan(text)
    # drop conditionals that hold no entry
    out, stack = [], []
    for l in body:
        if l.startswith('#') and re.match(r'#\s*(if|ifdef|ifndef)\b', l):
            stack.append([l])
        elif l.startswith('#') and re.match(r'#\s*(else|elif)\b', l):
            if stack:
                stack[-1].append(l)
        elif l.startswith('#') and re.match(r'#\s*endif\b', l):
            if stack:
                blk = stack.pop()
                if any(x.startswith('CG_STATIC') for x in blk):
                    blk.append(l)
                    (stack[-1] if stack else out).extend(blk)
        else:
            (stack[-1] if stack else out).append(l)
    print('/* SPDX-License-Identifier: MIT */')
    print('/* Copyright (c) 2026, viaGraph B.V. */')
    print('/* generated by gate/cg-statics.py from gate/cg_driver.c: every file-scope static object. Do not edit. */')
    for l in out:
        print(l)


if __name__ == '__main__':
    main()
