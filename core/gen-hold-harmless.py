"""
gen-hold-harmless.py - the hold-harmless set as merged, sorted ranges the policy compiler lays out.

Step 1 of every request is the hold-harmless lookup: an address in hold-harmless.txt (a root
server, a public resolver, a registry service prefix) is exempt from every rule. A linear scan of
the list would be the largest term in the default policy's cost, so the entries are merged here, at
generation, into sorted and non-overlapping [start, end] ranges per family (overlapping and adjacent
entries become one range), and the compiler lays each family out as FORMAT.md 4.2's rank structure
with the stride equal to one S-tree node's capacity: 16 keys at 32 bits, 4 at 128 bits. A descent
then reads one 64-byte node per level, the window is one line and the end check one line, so a
lookup costs d + 2 lines, d the smallest integer with (B+1)^d >= m.

The output also states the source counts and those depths, so a change to the list that moves the
cost moves a number in a committed file.

Usage:
    gen-hold-harmless.py [path/to/hold-harmless.txt]

Prints the C header to stdout; `make hold-harmless` writes we_hold_harmless.h. Regenerate it whenever
the list changes, never by hand.
"""
import ipaddress
import sys


def depth(m, fanout):
    d, p = 0, 1
    while p < m:
        p *= fanout
        d += 1
    return d


def merge(ranges):
    ranges.sort()
    out = []
    for s, e in ranges:
        if out and s <= out[-1][1] + 1:
            out[-1][1] = max(out[-1][1], e)
        else:
            out.append([s, e])
    return out


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "../hold-harmless.txt"
    v4, v6, total, distinct = [], [], 0, set()
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            net = ipaddress.ip_network(line.split()[0], strict=True)
            total += 1
            distinct.add(net)
            r = (int(net.network_address), int(net.broadcast_address))
            (v4 if net.version == 4 else v6).append(r)
    n4 = sum(1 for n in distinct if n.version == 4)
    n6 = len(distinct) - n4
    e4, e6 = len(v4), len(v6)
    m4, m6 = merge(v4), merge(v6)
    # window counts at the node-capacity strides, and the S-tree depth over them
    w4, w6 = (len(m4) + 15) // 16, (len(m6) + 3) // 4
    d4, d6 = depth(w4, 17), depth(w6, 5)
    print("/*\n * SPDX-License-Identifier: MIT\n * Copyright (c) 2026, viaGraph B.V.\n *\n"
          " * The hold-harmless set, merged. GENERATED by gen-hold-harmless.py from hold-harmless.txt:\n"
          " * regenerate with `make hold-harmless`, never by hand. Included by we_policy.c only.\n */")
    print("#ifndef WE_HOLD_HARMLESS_H\n#define WE_HOLD_HARMLESS_H\n")
    print("#include <stdint.h>\n")
    print("/* %d entries in the source (IPv4 %d, IPv6 %d), %d distinct (IPv4 %d, IPv6 %d). */"
          % (total, e4, e6, len(distinct), n4, n6))
    print("#define WE_HH_SOURCE_ENTRIES %du" % total)
    print("#define WE_HH_SOURCE_DISTINCT %du" % len(distinct))
    print("/* merged ranges, and the rank structure's windows (stride 16 at 32 bits, 4 at 128) and depth */")
    print("#define WE_HH_V4_COUNT %du" % len(m4))
    print("#define WE_HH_V6_COUNT %du" % len(m6))
    print("#define WE_HH_V4_WINDOWS %du" % w4)
    print("#define WE_HH_V6_WINDOWS %du" % w6)
    print("#define WE_HH_V4_DEPTH %du" % d4)
    print("#define WE_HH_V6_DEPTH %du" % d6)
    print("/* the lines a lookup at the maximum outcome class reads: depth + window + end */")
    print("#define WE_HH_V4_MAX_LINES %du" % (d4 + 2))
    print("#define WE_HH_V6_MAX_LINES %du" % (d6 + 2))
    print("\n/* [start, end], inclusive, host order */")
    print("static const uint32_t we_hh_v4[%d][2] = {" % max(len(m4), 1))
    for s, e in m4:
        print("    { 0x%08xu, 0x%08xu },  /* %s - %s */" % (s, e, ipaddress.IPv4Address(s), ipaddress.IPv4Address(e)))
    if not m4:
        print("    { 0u, 0u }")
    print("};")
    print("\n/* [start_hi, start_lo, end_hi, end_lo]: the 128-bit bounds as two 64-bit halves */")
    print("static const uint64_t we_hh_v6[%d][4] = {" % max(len(m6), 1))
    for s, e in m6:
        print("    { 0x%016xull, 0x%016xull, 0x%016xull, 0x%016xull },  /* %s - %s */"
              % (s >> 64, s & (2 ** 64 - 1), e >> 64, e & (2 ** 64 - 1),
                 ipaddress.IPv6Address(s).compressed, ipaddress.IPv6Address(e).compressed))
    if not m6:
        print("    { 0u, 0u, 0u, 0u }")
    print("};")
    print("\n#endif /* WE_HOLD_HARMLESS_H */")


if __name__ == "__main__":
    main()
